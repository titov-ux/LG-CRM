#!/bin/bash
# Генерим ~90с русской речи с паузами (имитация интервью: вопрос-ответ)
PHRASES=(
"Добрый день, Алексей. Расскажите, пожалуйста, о вашем опыте работы с микросервисной архитектурой."
"Последние три года я работал в финтех-компании, где мы разрабатывали платёжную платформу на Java и Spring Boot. У нас было около сорока микросервисов."
"Какие базы данных вы использовали в этом проекте?"
"В основном PostgreSQL для транзакционных данных и Redis для кеширования. Также применяли Kafka для обмена событиями между сервисами."
"Приходилось ли вам заниматься оптимизацией производительности?"
"Да, конечно. Например, мы ускорили обработку платежей в три раза за счёт батчинга запросов и переработки индексов в базе данных."
"Почему вы решили сменить место работы?"
"Хочу расти в сторону архитектурных задач, а в текущей команде такой возможности пока нет. Кроме того, интересен ваш стек технологий."
)
rm -f parts.txt; : > parts.txt
i=0
for p in "${PHRASES[@]}"; do
  espeak-ng -v ru -s 150 -w part_$i.wav "$p" 2>/dev/null
  ffmpeg -y -loglevel error -i part_$i.wav -ar 16000 -ac 1 part16_$i.wav
  echo "file 'part16_$i.wav'" >> parts.txt
  # пауза 1.2с между репликами
  ffmpeg -y -loglevel error -f lavfi -i anullsrc=r=16000:cl=mono -t 1.2 sil_$i.wav
  echo "file 'sil_$i.wav'" >> parts.txt
  i=$((i+1))
done
ffmpeg -y -loglevel error -f concat -safe 0 -i parts.txt -c copy interview_ru.wav
ffprobe -v error -show_entries format=duration -of csv=p=0 interview_ru.wav
